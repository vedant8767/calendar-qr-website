// month is 1-12
export function findSign(month, day) {
  const md = month * 100 + day;
  return signs.find(({ start, end }) => {
    const s = start[0] * 100 + start[1];
    const e = end[0] * 100 + end[1];
    return s <= e ? md >= s && md <= e : md >= s || md <= e;
  });
}
