// [{ title, name, date, template }] for every event dated on this day.
export function greetingsOnDay(year, monthIndex, day) {
  return Object.entries(events)
    .filter(([, e]) => {
      if (!e.date) return false;
      const [d, m, y] = e.date.split("/").map(Number);
      return y === year && m === monthIndex + 1 && d === day;
    })
    .map(([title, e]) => ({ title, ...e }));
}

export function getGreeting(title) {
  const e = events[title];
  return e ? { title, ...e } : null;
}
